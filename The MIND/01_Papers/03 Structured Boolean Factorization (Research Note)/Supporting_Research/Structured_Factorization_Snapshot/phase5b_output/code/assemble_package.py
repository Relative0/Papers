"""Create complete ZIP plus external SHA256, verify extraction and source integrity."""
from pathlib import Path
import datetime,hashlib,json,subprocess,sys,zipfile

OUT=Path(__file__).resolve().parents[1];ARCHIVE=OUT.parent/'continuity_archive'
NAME='STRUCTURED_FACTORIZATION_PHASE5B_2026-09-29'

def main():
    target=OUT/(NAME+'.zip')
    if target.exists():raise SystemExit('Refusing to overwrite an existing release ZIP')
    archive_record=json.loads((OUT/'data/archive_integrity.json').read_text())
    assert {p.relative_to(ARCHIVE).as_posix() for p in ARCHIVE.rglob('*') if p.is_file()}=={r['path'] for r in archive_record['files']}, 'Archive file set changed'
    for r in archive_record['files']:
        if hashlib.sha256((ARCHIVE/r['path']).read_bytes()).hexdigest()!=r['sha256']:
            raise SystemExit('Archive changed: '+r['path'])
    sources=[]
    for top,label in [(ARCHIVE,'continuity_archive'),(OUT,'phase5b_output')]:
        for p in sorted(top.rglob('*')):
            if not p.is_file():continue
            parts=p.relative_to(top).parts
            if label=='phase5b_output' and (any(x in ['.venv','__pycache__','package_verification'] for x in parts) or p.suffix=='.pyc' or p.name.startswith(NAME)):
                continue
            sources.append((label+'/'+p.relative_to(top).as_posix(),p.read_bytes()))
    readme='''# Structured Factorization Phase 5B complete package

Start with phase5b_output/PHASE5B_MASTER_REPORT.md, then NEXT_RESEARCH_GATE.md,
REPRODUCTION_AUDIT.md, BENCHMARK_RESULTS.md and HOSTILE_REVIEW_LEDGER.md.
REPRODUCIBILITY.md gives clean non-overwriting commands.

continuity_archive is the submitted continuity package, preserved byte for byte.
phase5b_output contains only the new research, exact code, measurements and reviews.
The local virtual environment and newly generated bytecode are excluded; exact
dependency versions are in requirements-lock.txt. Archived bytecode is retained as
original provenance but need not be executed.

SHA256SUMS.txt covers every content file and PACKAGE_MANIFEST.tsv. The checksum
file cannot hash itself. The outer ZIP SHA256 is supplied alongside the ZIP.
Run phase5b_output/code/verify_package.py on this extracted root to verify delivery.
'''
    sources.append(('README_FIRST.md',readme.encode()))
    manifest='path\tbytes\tsha256\n'+''.join(f'{name}\t{len(data)}\t{hashlib.sha256(data).hexdigest()}\n' for name,data in sources)
    sources.append(('PACKAGE_MANIFEST.tsv',manifest.encode()))
    sums=''.join(f'{hashlib.sha256(data).hexdigest()}  {name}\n' for name,data in sources)
    sources.append(('SHA256SUMS.txt',sums.encode()))
    with zipfile.ZipFile(target,'x',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,data in sources:z.writestr(NAME+'/'+name,data)
    digest=hashlib.sha256(target.read_bytes()).hexdigest()
    target.with_suffix('.zip.sha256').write_text(f'{digest}  {target.name}\n')
    verification=OUT/'package_verification'
    if verification.exists():raise SystemExit('Verification target exists; use a new output package directory')
    verification.mkdir()
    # Extended paths avoid Windows MAX_PATH failures in the preserved nested archive.
    extraction_root=Path('\\\\?\\'+str(verification)) if sys.platform=='win32' else verification
    with zipfile.ZipFile(target) as z:
        if z.testzip() is not None:raise SystemExit('ZIP CRC failure')
        z.extractall(extraction_root)
    p=subprocess.run([sys.executable,'-B',str(extraction_root/NAME/'phase5b_output/code/verify_package.py')],text=True,capture_output=True)
    print(p.stdout,end='');print(p.stderr,end='',file=sys.stderr)
    if p.returncode:raise SystemExit(p.returncode)
    receipt={'zip':str(target),'sha256':digest,'bytes':target.stat().st_size,'entries':len(sources),
             'archive_files_unchanged':len(archive_record['files']),'verification':'PASS',
             'utc':datetime.datetime.now(datetime.timezone.utc).isoformat()}
    (OUT/(NAME+'_RECEIPT.json')).write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(receipt,indent=2))

if __name__=='__main__':main()
