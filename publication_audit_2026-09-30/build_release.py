def digest(b): return hashlib.sha256(b).hexdigest()
def scan(name, data, depth=0):
    parts = Path(name).parts
    if any(x.startswith('.env') or x in ('id_rsa','id_ed25519') for x in parts):
        raise ValueError('Sensitive filename: '+name)
    if secret.search(data): raise ValueError('Credential-pattern match: '+name)
    if name.lower().endswith('.zip'):
        if depth > 8: raise ValueError('Archive depth: '+name)
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            for item in z.infolist():
                if not item.is_dir(): scan(name+'!'+item.filename,z.read(item),depth+1)

def publish(src, rel):
    data = src.read_bytes(); scan(rel,data)
    dest=OUT/rel; dest.parent.mkdir(parents=True,exist_ok=True); dest.write_bytes(data)
    records[rel]={'bytes':len(data),'sha256':digest(data),'source':str(src)}

def publish_member(archive, member, rel):
    with zipfile.ZipFile(archive) as source:
        data=source.read(member)
    scan(rel,data)
    dest=OUT/rel; dest.parent.mkdir(parents=True,exist_ok=True); dest.write_bytes(data)
    records[rel]={'bytes':len(data),'sha256':digest(data),'source':str(archive)+'!'+member}

def bundle(name, roots):
    entries=[]
    dest=OUT/name; dest.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(dest,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for root in roots:
            source,prefix=root[:2]
            if len(root)==3:
                member_prefix=root[2]
                with zipfile.ZipFile(source) as archived:
                    candidates=[(Path(prefix,name).as_posix(),archived.read(name)) for name in sorted(archived.namelist()) if name.startswith(member_prefix) and not name.endswith('/')]
            else:
                files=sorted(source.rglob('*')) if source.is_dir() else [source]
                candidates=(((Path(prefix)/p.relative_to(source)).as_posix() if source.is_dir() else prefix,p.read_bytes()) for p in files if p.is_file() and not any(x in ('__pycache__','.pytest_cache','.git','.venv','venv') for x in p.parts))
            for rel,data in candidates:
                p=Path(rel)
                if p.name == 'ispras-hdl-benchmarks-10c3fb51d0810ce862659211862660dcc270a6af.zip':
                    exclusions.append({'package':name,'path':rel,'reason':'Redundant upstream download; extracted natural_sources corpus and its provenance are included.','bytes':len(data),'sha256':digest(data)})
                    continue
                if p.suffix.lower() in ('.exe','.dll','.pyc'):
                    exclusions.append({'package':name,'path':rel,'reason':'Third-party Windows binary redistribution unresolved, or generated bytecode; retained locally.','bytes':len(data)})
                    continue
                scan(rel,data)
                info=zipfile.ZipInfo(rel,(2026,9,30,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
                z.writestr(info,data)
                entries.append({'path':rel,'bytes':len(data),'sha256':digest(data)})
        z.writestr('PUBLICATION_CONTENTS.json',json.dumps({'files':entries,'note':'Publication snapshot only; original evidence bytes unchanged. Commands are historical, not execution authorization.'},indent=2))
    data=dest.read_bytes()
    assert len(data)<95_000_000,(name,len(data))
    records[name]={'bytes':len(data),'sha256':digest(data),'source_roots':[str(x[0]) for x in roots],'members':len(entries)}
    scans.append({'package':name,'files':len(entries),'credential_pattern_scan':'PASS'})

